-- Guestbook: notes on the wall, the admin, and photo storage.
--
-- Who can do what (enforced here, not just in the app):
--   * anyone            can read visible notes and view photos
--   * signed-in visitor can add a note as themselves (anonymous sign-in counts),
--                       and upload photos into their own folder only
--   * the admin         can also see hidden notes, hide/unhide any note,
--                       and move any note
--   * nobody (via the API) can edit a note's content or delete notes
--
-- Positions are wall units (see src/wall/coordinates.ts): the wall is
-- 1600 x 1100 and (x, y) is the note's centre.

-- ---------------------------------------------------------------------------
-- Admins
-- ---------------------------------------------------------------------------

create table public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

-- Nobody reads or writes this table through the API; it's managed with SQL.
alter table public.admins enable row level security;

create function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- ---------------------------------------------------------------------------
-- Entries (notes on the wall)
-- ---------------------------------------------------------------------------

-- Stacking order: every new (or moved) note goes on top of everything else.
create sequence public.entries_z_index_seq;

create table public.entries (
  -- Generated by the app so it can show the note before it's saved.
  id uuid primary key,
  type text not null check (type in ('sticky', 'polaroid')),

  -- Sticky notes
  shape text check (shape in ('square', 'apple', 'clover')),
  color text check (color in ('yellow', 'pink', 'blue', 'green', 'orange')),

  -- Polaroids: a photo (stored in the "photos" bucket) or a doodle
  media_kind text check (media_kind in ('photo', 'doodle')),
  image_path text check (char_length(image_path) <= 200),
  photo_filter text not null default 'none' check (photo_filter in ('none', 'warm', 'mono', 'faded')),

  -- Strokes for either kind; capped at ~300 KB so one note can't bloat the wall.
  doodle jsonb check (doodle is null or octet_length(doodle::text) <= 300000),

  message text check (char_length(message) between 1 and 320),
  name text check (char_length(name) between 1 and 40),

  x real not null check (x between 0 and 1600),
  y real not null check (y between 0 and 1100),
  rotation real not null check (rotation between -15 and 15),
  -- Assigned by the insert/update triggers (never by visitors).
  z_index bigint not null,
  attachment text not null check (attachment in ('washi-tape', 'pin', 'double-sided-tape')),

  owner_id uuid default auth.uid() references auth.users (id) on delete set null,
  hidden boolean not null default false,
  created_at timestamptz not null default now(),

  -- Stickies have a shape and colour; Polaroids have media.
  constraint sticky_has_shape check (type <> 'sticky' or (shape is not null and color is not null)),
  constraint polaroid_has_media check (type <> 'polaroid' or media_kind is not null),
  constraint photo_has_path check (media_kind is distinct from 'photo' or image_path is not null),
  constraint doodle_media_has_doodle check (media_kind is distinct from 'doodle' or doodle is not null),
  -- A sticky needs writing or a doodle (at least one).
  constraint sticky_has_content check (type <> 'sticky' or message is not null or doodle is not null),
  -- The visible limit: 50 words.
  constraint message_word_limit check (
    message is null or array_length(regexp_split_to_array(btrim(message), '\s+'), 1) <= 50
  )
);

alter sequence public.entries_z_index_seq owned by public.entries.z_index;

create index entries_visible_idx on public.entries (created_at) where not hidden;
create index entries_owner_idx on public.entries (owner_id);

alter table public.entries enable row level security;

-- Column-level access: visitors only ever send content and position. The
-- server decides owner, stacking order, timestamps and the hidden flag.
revoke all on public.entries from anon, authenticated;
grant select on public.entries to anon, authenticated;
grant insert (
  id, type, shape, color, media_kind, image_path, photo_filter, doodle,
  message, name, x, y, rotation, attachment
) on public.entries to authenticated;
-- Only position and the hidden flag can ever change after posting
-- (and the policies below say who may change them).
grant update (x, y, rotation, hidden) on public.entries to authenticated;

-- Read: visible notes for everyone; the admin also sees hidden ones.
create policy "Visible notes are public"
  on public.entries for select
  to anon, authenticated
  using (not hidden or public.is_admin());

-- Add: signed-in visitors (including anonymous ones), as themselves, and a
-- photo must live in their own folder.
create policy "Visitors add their own notes"
  on public.entries for insert
  to authenticated
  with check (
    owner_id = auth.uid()
    and (image_path is null or image_path like auth.uid()::text || '/%')
  );

-- Change: the admin can move or hide any note.
-- (Visitors moving their own note is a later feature: it will get its own
-- policy, and the guard below already stops them touching `hidden`.)
create policy "Admin moves and hides notes"
  on public.entries for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- No delete policy: notes are removed by hiding them (or via the dashboard).

-- ---------------------------------------------------------------------------
-- Server-side rules on writes
-- ---------------------------------------------------------------------------

-- New notes: stamp owner/time/stacking server-side and slow down floods
-- (one note per visitor per minute; the admin is exempt).
create function public.entries_before_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  new.owner_id := auth.uid();
  new.created_at := now();
  new.hidden := false;
  new.z_index := nextval('public.entries_z_index_seq');

  if not public.is_admin() and exists (
    select 1 from public.entries
    where owner_id = new.owner_id and created_at > now() - interval '1 minute'
  ) then
    raise exception 'Please wait a minute before adding another note.'
      using errcode = 'P0001', hint = 'rate_limited';
  end if;

  return new;
end;
$$;

create trigger entries_before_insert
  before insert on public.entries
  for each row execute function public.entries_before_insert();

-- Updates: only the admin may hide/unhide; a moved note comes to the top.
create function public.entries_before_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.hidden is distinct from old.hidden and not public.is_admin() then
    raise exception 'Only the admin can hide or unhide notes.' using errcode = '42501';
  end if;

  if new.x is distinct from old.x or new.y is distinct from old.y then
    new.z_index := nextval('public.entries_z_index_seq');
  end if;

  return new;
end;
$$;

create trigger entries_before_update
  before update on public.entries
  for each row execute function public.entries_before_update();

-- Live updates: new and changed notes are pushed to everyone viewing
-- (subject to the same read policy, so hidden notes reach only the admin).
alter publication supabase_realtime add table public.entries;

-- ---------------------------------------------------------------------------
-- Photo storage
-- ---------------------------------------------------------------------------

-- Public bucket: anyone can view photos by URL. Uploads are resized in the
-- browser first (longest side 1200px), so the 10 MB cap is a safety net.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('photos', 'photos', true, 10485760, array['image/jpeg', 'image/png', 'image/webp']);

-- Visitors upload only into a folder named after themselves: <user id>/<entry id>.jpg
create policy "Visitors upload photos to their own folder"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'photos'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

-- No update/delete policies: photos can't be replaced or removed via the API.
